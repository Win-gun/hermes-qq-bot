import assert from "node:assert/strict";
import { createTaskDelivery } from "../src/task-delivery.js";
let writes = 0, allowed = true;
const task = { id: "task_fixture", accountId: "a", logicalBotId: "account:a", attemptId: "attempt_a", grantRevision: 1, status: "running" };
const prepare = createTaskDelivery({ getTask: () => task, persist: () => { writes++; }, isCurrent: () => allowed });
const a = prepare(task, { key: "notice" });
assert.equal(a.isCurrent(), true); assert.equal(writes, 0);
task.status = "completed"; assert.equal(a.isCurrent(), false);
task.status = "running";
const b = prepare(task, { key: "notice" }); b.onSendStarted(); assert.equal(writes, 1);
assert.throws(() => b.onSendStarted()); b.settle(false);
assert.equal(task.deliveryLedger[0].status, "uncertain");
assert.equal(prepare(task, { key: "notice" }).isCurrent(), false);
const c = prepare(task, { key: "artifact" }); task.grantRevision++; assert.equal(c.isCurrent(), false);
const d = prepare(task, { key: "other" }); allowed = false; assert.throws(() => d.onSendStarted());
allowed = true;
const e = prepare(task, { key: "last" }); e.onSendStarted(); e.settle(true);
assert.equal(task.deliveryLedger.at(-1).status, "confirmed");
assert.equal(prepare(task, { key: "last" }).isCurrent(), false);
task.authorityBlocked = true;
const blocked = prepare(task, { key: "blocked" });
assert.equal(blocked.isCurrent(), false); assert.throws(() => blocked.onSendStarted());
console.log(JSON.stringify({ ok: true, tests: 14, fixtureOnly: true, qqSends: 0 }));
